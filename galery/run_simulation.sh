#!/bin/bash

# Скрипт запуска симуляции картинной галереи
# Автор: [Ваше ФИО]
# Группа: [Ваша группа]

echo "🚀 Запуск симуляции картинной галереи"
echo "========================================"

# Проверка компиляции
echo "📦 Проверка компиляции программ..."
make all

if [ $? -ne 0 ]; then
    echo "❌ Ошибка компиляции!"
    exit 1
fi

echo "✅ Компиляция успешна"

# Очистка предыдущих ресурсов
echo "🧹 Очистка предыдущих ресурсов..."
./cleanup

echo "🔄 Запуск процессов..."
echo "========================================"

# Запуск вахтера в фоне
echo "🚨 Запуск вахтера..."
./watcher &
WATCHER_PID=$!
echo "Вахтер запущен с PID: $WATCHER_PID"

sleep 2

# Запуск нескольких наблюдателей
echo "👁️ Запуск наблюдателей..."
./observer 1 &
OBSERVER1_PID=$!
echo "Наблюдатель 1 запущен с PID: $OBSERVER1_PID"

./observer 2 &
OBSERVER2_PID=$!
echo "Наблюдатель 2 запущен с PID: $OBSERVER2_PID"

./observer 3 &
OBSERVER3_PID=$!
echo "Наблюдатель 3 запущен с PID: $OBSERVER3_PID"

sleep 2

# Запуск посетителей
echo "👥 Запуск посетителей..."
for i in $(seq 1 50); do
    ./visitor $i &
    VISITOR_PIDS[$i]=$!
    echo "Посетитель $i запущен с PID: ${VISITOR_PIDS[$i]}"
    sleep 0.1
done

echo "========================================"
echo "⏳ Симуляция запущена. Ожидание завершения..."
echo "Симуляция будет работать 30 секунд..."

# Ожидание завершения вахтера
wait $WATCHER_PID

echo "========================================"
echo "🛑 Завершение симуляции..."

# Остановка всех процессов
echo "Остановка наблюдателей..."
kill $OBSERVER1_PID $OBSERVER2_PID $OBSERVER3_PID 2>/dev/null

echo "Остановка посетителей..."
for i in $(seq 1 50); do
    kill ${VISITOR_PIDS[$i]} 2>/dev/null
done

# Очистка ресурсов
echo "Очистка ресурсов..."
./cleanup

echo "========================================"
echo "✅ Симуляция завершена!"
echo "Для просмотра логов проверьте вывод в консолях наблюдателей"